#!/usr/bin/env python3
"""Convert Spleen BDF fonts into the embedded bitmap tables in src/font_data.rs.

The fonts are not vendored. Fetch the pinned release, unpack it, and point this
script at the directory:

    curl -LO https://github.com/fcambus/spleen/releases/download/2.2.0/spleen-2.2.0.tar.gz
    # sha256 ec42925c6b56d2138c862b2f97147c872e472f674bf03423417d827a08d69a89
    tar xzf spleen-2.2.0.tar.gz
    python3 screen/tools/bdf2rs.py spleen-2.2.0 > screen/src/font_data.rs

Only printable ASCII plus a few symbols the screen draws are kept.
"""
import sys
from pathlib import Path

SIZES = [(8, 16), (12, 24), (16, 32), (32, 64)]
EXTRA = [0x00B0, 0x00B7, 0x2191, 0x2193, 0x2502, 0x2588, 0x2591, 0x2592, 0x2593, 0x25B2, 0x25BC]
WANTED = set(range(0x20, 0x7F)) | set(EXTRA)


def parse(path):
    glyphs = {}
    lines = Path(path).read_text().splitlines()
    ascent = next(int(l.split()[1]) for l in lines if l.startswith('FONT_ASCENT '))
    i = 0
    while i < len(lines):
        if not lines[i].startswith('STARTCHAR'):
            i += 1
            continue
        code, bbx, rows = None, None, []
        i += 1
        while not lines[i].startswith('ENDCHAR'):
            line = lines[i]
            if line.startswith('ENCODING '):
                code = int(line.split()[1])
            elif line.startswith('BBX '):
                bbx = tuple(int(v) for v in line.split()[1:])
            elif line == 'BITMAP':
                i += 1
                while not lines[i].startswith('ENDCHAR'):
                    rows.append(int(lines[i], 16))
                    i += 1
                break
            i += 1
        if code in WANTED:
            glyphs[code] = (bbx, rows)
        i += 1
    return ascent, glyphs


def cell(width, height, ascent, bbx, rows):
    """Place a glyph's rows into a width x height cell, one int per row, MSB = left."""
    gw, gh, gx, gy = bbx
    row_bits = ((gw + 7) // 8) * 8
    out = [0] * height
    top = ascent - (gy + gh)
    for r, bits in enumerate(rows):
        y = top + r
        if not 0 <= y < height:
            continue
        for c in range(gw):
            if bits & (1 << (row_bits - 1 - c)):
                x = gx + c
                if 0 <= x < width:
                    out[y] |= 1 << (width - 1 - x)
    return out


def main():
    root = Path(sys.argv[1])
    print('// Generated by screen/tools/bdf2rs.py from Spleen 2.2.0 (BSD-2-Clause,')
    print('// Copyright (c) 2018-2026 Frederic Cambus; see screen/fonts/LICENSE.spleen).')
    print('// Do not edit by hand.')
    print()
    print('use crate::font::Font;')
    for width, height in SIZES:
        ascent, glyphs = parse(root / f'spleen-{width}x{height}.bdf')
        codes = sorted(glyphs)
        missing = sorted(WANTED - set(codes))
        if any(c < 0x7F for c in missing):
            raise SystemExit(f'{width}x{height} lacks ASCII glyphs: {missing}')
        row_type = {8: 'u8', 12: 'u16', 16: 'u16', 32: 'u32'}[width]
        name = f'SPLEEN_{width}X{height}'
        print()
        print(f'static {name}_CODES: [u32; {len(codes)}] = [')
        for start in range(0, len(codes), 12):
            print('    ' + ', '.join(f'0x{c:04X}' for c in codes[start:start + 12]) + ',')
        print('];')
        print(f'static {name}_ROWS: [{row_type}; {len(codes) * height}] = [')
        for code in codes:
            rows = cell(width, height, ascent, *glyphs[code])
            digits = (width + 3) // 4
            print('    ' + ', '.join(f'0x{r:0{digits}X}' for r in rows) + f',  // U+{code:04X}')
        print('];')
        print(f'pub static {name}: Font<{row_type}> = Font {{')
        print(f'    width: {width},')
        print(f'    height: {height},')
        print(f'    codes: &{name}_CODES,')
        print(f'    rows: &{name}_ROWS,')
        print('};')


if __name__ == '__main__':
    main()
